import { and, eq } from "drizzle-orm";
import { z } from "zod";
import { db } from "@/db";
import * as schema from "@/db/schema/app-schema";
import { resolveLocalUploadPath } from "./storage";

/**
 * Helpers of the Diplomation REST API (`/api/diplomation/**`). Every request
 * is authenticated by an API key bound to one institution: whatever the
 * client sends, it only reads and writes that institution's records.
 */

type ApiKeyScope = { id: string; institutionId: string };

const documentSchema = z.object({
	sourceId: z.string().min(1).max(200),
	documentType: z.string().min(1).max(100),
	studentId: z.string().min(1).nullish(),
	generatedAt: z.union([z.string(), z.number()]).nullish(),
	fileReference: z.string().max(2000).nullish(),
});

/**
 * Logs a document generated by Diplomation. A student of another institution
 * is answered 404, like an unknown one.
 */
export async function recordDiplomationDocument(
	apiKey: ApiKeyScope,
	body: unknown,
): Promise<{ status: 200 | 400 | 404; body: Record<string, unknown> }> {
	const parsed = documentSchema.safeParse(body);
	if (!parsed.success)
		return { status: 400, body: { error: "Invalid document payload" } };
	const input = parsed.data;
	if (input.studentId) {
		const student = await db.query.students.findFirst({
			where: and(
				eq(schema.students.id, input.studentId),
				eq(schema.students.institutionId, apiKey.institutionId),
			),
			columns: { id: true },
		});
		if (!student) return { status: 404, body: { error: "Student not found" } };
	}
	const generatedAt = new Date(input.generatedAt ?? Date.now());
	if (Number.isNaN(generatedAt.getTime()))
		return { status: 400, body: { error: "Invalid generatedAt" } };
	await db.insert(schema.diplomationDocuments).values({
		institutionId: apiKey.institutionId,
		sourceId: input.sourceId,
		documentType: input.documentType,
		studentId: input.studentId ?? null,
		generatedAt,
		fileReference: input.fileReference ?? null,
		generatedByApiKeyId: apiKey.id,
	});
	return { status: 200, body: { ok: true } };
}

/**
 * Resolve a logoUrl (relative path or full URL) and return its base64 data-URL.
 * Returns null if the file doesn't exist, the fetch fails, the answer is not an
 * image, or a local path would leave the uploads folder (`../`) or point into
 * the private guided-import folder — a logo URL is set by an institution admin
 * and must never turn into a way to read server files.
 */
export async function logoUrlToBase64(logoUrl: string): Promise<string | null> {
	try {
		let buffer: ArrayBuffer;
		let mimeType = "image/png";

		if (logoUrl.startsWith("http://") || logoUrl.startsWith("https://")) {
			const res = await fetch(logoUrl, { redirect: "error" });
			if (!res.ok) return null;
			const ct = res.headers.get("content-type")?.split(";")[0].trim();
			if (!ct?.startsWith("image/")) return null;
			mimeType = ct;
			buffer = await res.arrayBuffer();
		} else {
			const uploadsPublicPath =
				process.env.STORAGE_LOCAL_PUBLIC_PATH ?? "/uploads";
			const relativePath = (
				logoUrl.startsWith(uploadsPublicPath)
					? logoUrl.slice(uploadsPublicPath.length)
					: logoUrl
			).replace(/^\/+/, "");
			if (relativePath.split("/")[0] === "imports") return null;
			const filePath = resolveLocalUploadPath(relativePath);
			if (!filePath) return null;
			const file = Bun.file(filePath);
			if (!(await file.exists())) return null;
			mimeType = file.type || "image/png";
			if (!mimeType.startsWith("image/")) return null;
			buffer = await file.arrayBuffer();
		}

		const base64 = Buffer.from(buffer).toString("base64");
		return `data:${mimeType};base64,${base64}`;
	} catch {
		return null;
	}
}
