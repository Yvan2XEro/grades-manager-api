// ─── 9. Sample assessments ────────────────────────────────────────────────────

async function ensureAssessments(
	institutionId: string,
	classId: string,
	termId: string,
	studentIds: string[],
	subjectList: Array<{ id: string; name: string }>,
	adminStaffId: string,
) {
	// Check if assessments already seeded
	const existing = await db
		.select()
		.from(assessments)
		.where(eq(assessments.classId, classId))
		.limit(1);
	if (existing[0]) {
		await log("Assessments already seeded");
		return;
	}

	const mathSubject = subjectList.find((s) => s.name === "Mathematics");
	const frSubject = subjectList.find((s) => s.name === "French");
	if (!mathSubject || !frSubject) return;

	const rows = [];
	for (const studentId of studentIds) {
		// Seq 1 + Seq 2 for Math
		const mathSeq1 = 10 + Math.random() * 9;
		const mathSeq2 = 10 + Math.random() * 9;
		rows.push(
			{
				institutionId,
				studentId,
				classId,
				termId,
				subjectId: mathSubject.id,
				assessmentType: "sequence_1" as const,
				value: mathSeq1.toFixed(2),
				enteredById: adminStaffId,
			},
			{
				institutionId,
				studentId,
				classId,
				termId,
				subjectId: mathSubject.id,
				assessmentType: "sequence_2" as const,
				value: mathSeq2.toFixed(2),
				enteredById: adminStaffId,
			},
		);

		// Seq 1 + Seq 2 for French
		const frSeq1 = 8 + Math.random() * 11;
		const frSeq2 = 8 + Math.random() * 11;
		rows.push(
			{
				institutionId,
				studentId,
				classId,
				termId,
				subjectId: frSubject.id,
				assessmentType: "sequence_1" as const,
				value: frSeq1.toFixed(2),
				enteredById: adminStaffId,
			},
			{
				institutionId,
				studentId,
				classId,
				termId,
				subjectId: frSubject.id,
				assessmentType: "sequence_2" as const,
				value: frSeq2.toFixed(2),
				enteredById: adminStaffId,
			},
		);
	}

	await db.insert(assessments).values(rows).onConflictDoNothing();
	await log(
		`Created ${rows.length} sample assessments (Math + French, Seq 1-2)`,
	);
}

// ─── 9. Subject Assignments ───────────────────────────────────────────────────

async function ensureSubjectAssignments(
	institutionId: string,
	academicYearId: string,
	classId: string,
	staffId: string,
	subjectList: Array<{ id: string; name: string }>,
): Promise<void> {
	const existing = await db
		.select({ id: subjectAssignments.id })
		.from(subjectAssignments)
		.where(eq(subjectAssignments.classId, classId))
		.limit(1);
	if (existing.length > 0) {
		await log("Subject assignments already exist");
		return;
	}
	await db.insert(subjectAssignments).values(
		subjectList.map((s) => ({
			institutionId,
			academicYearId,
			classId,
			subjectId: s.id,
			staffId,
		})),
	);
	await log(`Created ${subjectList.length} subject assignments`);
}

// ─── Main ─────────────────────────────────────────────────────────────────────

async function main() {
	console.log("\n🌱  TKAMS Secondaire — Seed\n");

	// Ensure all tables exist (runs migrations + auth table DDL for PGlite)
	await pushSchema();

	const adminUserId = await ensureAdminUser();
	const { institutionId, staffId } = await ensureInstitution(adminUserId);
	const academicYearId = await ensureAcademicYear(institutionId);
	const termIds = await ensureTerms(institutionId, academicYearId);
	const trackIds = await ensureTracks(institutionId);
	const subjectList = await ensureSubjects(institutionId);
	const classId = await ensureClass(
		institutionId,
		academicYearId,
		trackIds[0]!,
	);
	await ensureSubjectAssignments(
		institutionId,
		academicYearId,
		classId,
		staffId,
		subjectList,
	);

	const studentIds = await ensureStudents(
		institutionId,
		academicYearId,
		classId,
	);

	// Seed assessments for term 1 (index 0)
	await ensureAssessments(
		institutionId,
		classId,
		termIds[0]!,
		studentIds,
		subjectList,
		staffId,
	);

	console.log(`
✅  Seed complete!

  Institution : ${SCHOOL_NAME}
  Admin login : ${ADMIN_EMAIL}
  Password    : ${ADMIN_PASSWORD}

  Org ID (set as active org in the app): ${institutionId}

  To log in:
    1. Start the server:  bun dev:server
    2. Start the client:  bun dev:client
    3. Go to http://localhost:5173 and sign in with the credentials above.
    4. The first sign-in will not have an active org — the app will
       ask you to select one. Pick "${SCHOOL_NAME}".
`);
}

main().catch((err) => {
	console.error("❌  Seed failed:", err);
	process.exit(1);
});
