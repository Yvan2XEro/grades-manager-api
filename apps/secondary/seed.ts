const ADMIN_EMAIL = process.env.SYSTEM_ADMIN_EMAIL ?? "admin@tkams.io";
const ADMIN_PASSWORD = process.env.SYSTEM_ADMIN_PASSWORD ?? "Admin1234!";
const SCHOOL_NAME = "Lycée de Démonstration";
const SCHOOL_CITY = "Yaoundé";
const ACADEMIC_YEAR = "2025-2026";

async function log(msg: string) {
	console.log(`  ▸ ${msg}`);
}

// ─── 1. Auth user (admin) ─────────────────────────────────────────────────────

async function ensureAdminUser(): Promise<string> {
	// Check if user already exists
	const existing = await db
		.select({ id: user.id })
		.from(user)
		.where(eq(user.email, ADMIN_EMAIL))
		.limit(1);

	if (existing[0]) {
		await log(
			`Auth user already exists: ${ADMIN_EMAIL} (id=${existing[0].id})`,
		);
		return existing[0].id;
	}

	const userId = randomUUID();
	// Use Better-Auth's own hashPassword so the format matches exactly.
	const hashedPassword = await hashPassword(ADMIN_PASSWORD);

	await db.insert(user).values({
		id: userId,
		name: "Administrateur Système",
		email: ADMIN_EMAIL,
		emailVerified: true,
		createdAt: new Date(),
		updatedAt: new Date(),
	});

	// Insert the credential account (providerId = "credential" for email/password)
	await db.insert(account).values({
		id: randomUUID(),
		userId,
		accountId: ADMIN_EMAIL,
		providerId: "credential",
		issuer: "credential",
		password: hashedPassword,
		createdAt: new Date(),
		updatedAt: new Date(),
	});

	await log(`Created auth user: ${ADMIN_EMAIL} (id=${userId})`);
	return userId;
}

// ─── 2. Institution + Better-Auth org ────────────────────────────────────────

async function ensureInstitution(
	adminUserId: string,
): Promise<{ institutionId: string; staffId: string }> {
	// Check if institution already exists for this slug
	const slug = "lycee-demo";
	const existingOrg = await db
		.select({ id: organization.id })
		.from(organization)
		.where(eq(organization.slug, slug))
		.limit(1);
	if (existingOrg[0]?.id) {
		const institutionId = existingOrg[0].id;
		// Find the admin staff record
		const existingStaff = await db
			.select()
			.from(staff)
			.where(eq(staff.authUserId, adminUserId))
			.limit(1);
		const staffId = existingStaff[0]?.id ?? adminUserId;
		await log(`Institution already exists (id=${institutionId})`);
		return { institutionId, staffId };
	}

	const orgId = randomUUID();

	// Better-Auth organization row
	await db
		.insert(organization)
		.values({
			id: orgId,
			name: SCHOOL_NAME,
			slug,
			createdAt: new Date(),
		})
		.onConflictDoNothing();

	// Application institution
	await db
		.insert(institutions)
		.values({
			id: orgId,
			name: SCHOOL_NAME,
			city: SCHOOL_CITY,
			type: "lycee",
			assessmentMode: "six_sequence",
		})
		.onConflictDoNothing();

	// Staff record for admin (id auto-generated by id() helper)
	const [adminStaff] = await db
		.insert(staff)
		.values({
			institutionId: orgId,
			authUserId: adminUserId,
			firstName: "Administrateur",
			lastName: "Système",
			email: ADMIN_EMAIL,
			role: "admin",
		})
		.returning();

	// Better-Auth member (admin role)
	await db
		.insert(member)
		.values({
			id: randomUUID(),
			organizationId: orgId,
			userId: adminUserId,
			role: "admin",
			createdAt: new Date(),
		})
		.onConflictDoNothing();

	await log(
		`Created institution: ${SCHOOL_NAME} (id=${orgId}, staffId=${adminStaff?.id})`,
	);
	return { institutionId: orgId, staffId: adminStaff?.id };
}

// ─── 3. Academic year ─────────────────────────────────────────────────────────

